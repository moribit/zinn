const std = @import("std");
const zinn = @import("zinn");
pub fn build(b: *std.Build) void {
    const dep = b.dependency("zinn", .{});
    const core = b.createModule(.{ .root_source_file = dep.path("src/root.zig"), .target = b.graph.host, .optimize = .fast });
    const test_options = b.standardOptimizeOption(.{});
    const tests = b.addTest(.{ .root_module = b.createModule(.{ .root_source_file = b.path("tests.zig"), .target = b.graph.host, .optimize = test_options }) });
    tests.root_module.addImport("zinn", core);
    b.step("test", "Environment and training integration tests").dependOn(&b.addRunArtifact(tests).step);
    const opts = b.addOptions();
    const export_profile = b.option(enum { baseline, improved }, "policy-export", "CartPole export profile (baseline remains compatible)") orelse .baseline;
    opts.addOption(bool, "improved", export_profile == .improved);
    const seed = b.option(u32, "seed", "Reproducible seed") orelse 42;
    opts.addOption(u32, "seed", seed);
    opts.addOption(usize, "episodes", b.option(usize, "episodes", "Training episodes") orelse 1000);
    opts.addOption(usize, "replay_capacity", b.option(usize, "replay-capacity", "Replay transitions") orelse 10000);
    opts.addOption(f32, "rate", b.option(f32, "rate", "SGD learning rate") orelse 0.005);
    opts.addOption(f32, "gamma", b.option(f32, "gamma", "Discount factor") orelse 0.95);
    opts.addOption(f32, "epsilon_start", b.option(f32, "epsilon-start", "Initial exploration") orelse 1);
    opts.addOption(f32, "epsilon_end", b.option(f32, "epsilon-end", "Minimum exploration") orelse 0.05);
    opts.addOption(usize, "epsilon_steps", b.option(usize, "epsilon-steps", "Linear decay steps") orelse 10000);
    opts.addOption(usize, "train_every", b.option(usize, "train-every", "Steps per SGD update") orelse 1);
    opts.addOption(f32, "reward_scale", b.option(f32, "reward-scale", "TD reward scale") orelse 1);
    opts.addOption(usize, "batch", b.option(usize, "batch", "Mini-batch size") orelse 32);
    opts.addOption(usize, "target_interval", b.option(usize, "target-interval", "Target sync per gradient updates") orelse 100);
    const module = b.createModule(.{ .root_source_file = b.path("train.zig"), .target = b.graph.host, .optimize = .fast });
    module.addImport("zinn", core);
    module.addImport("options", opts.createModule());
    const exe = b.addExecutable(.{ .name = "cartpole-train", .root_module = module });
    const run = b.addRunArtifact(exe);
    const progress = b.option(zinn.ProgressMode, "progress", "auto/plain/off") orelse .auto;
    zinn.ProgressBuild.configure(run, progress, "CartPole DQN train/export");
    const checkpoint = run.addOutputFileArg("policy.zinn");
    const curve = run.addOutputFileArg("curve.csv");
    const report = run.addOutputFileArg("report.json");
    const source = run.addOutputFileArg("policy.zig");
    const metadata = run.addOutputFileArg("policy.json");
    const calibration = run.addOutputFileArg("calibration.csv");
    if (b.option([]const u8, "checkpoint", "Load an existing policy instead of training")) |path| run.addFileArg(.{ .cwd_relative = path }) else run.addArg("-");
    if (b.option([]const u8, "calibration", "Reuse normalized calibration CSV")) |path| run.addFileArg(.{ .cwd_relative = path }) else run.addArg("-");
    const steps = zinn.ProgressBuild.operation(b, dep.builder, run, progress, "cartpole", "train", "training/cartpole.zinn", .train, b.path("build.zig"));
    const train = steps.backend;
    train.dependOn(&b.addInstallFile(source, "models/policy.zig").step);
    train.dependOn(&b.addInstallFile(metadata, "reports/policy.json").step);
    train.dependOn(&b.addInstallFile(calibration, "reports/calibration.csv").step);
    train.dependOn(&b.addInstallFile(checkpoint, "training/cartpole.zinn").step);
    train.dependOn(&b.addInstallFile(curve, "reports/curve.csv").step);
    train.dependOn(&b.addInstallFile(report, "reports/report.json").step);

    const stability_exe = b.addExecutable(.{ .name = "cartpole-stability", .root_module = b.createModule(.{ .root_source_file = b.path("stability.zig"), .target = b.graph.host, .optimize = .fast }) });
    stability_exe.root_module.addImport("zinn", core);
    const stability = b.addRunArtifact(stability_exe);
    stability.addArg(b.fmt("{d}", .{seed}));
    const stability_dir = stability.addOutputDirectoryArg("stability");
    b.step("stability", "Isolated fixed-rate versus step-decay learning experiment").dependOn(&b.addInstallDirectory(.{ .source_dir = stability_dir, .install_dir = .prefix, .install_subdir = "reports/stability" }).step);
    const study_exe = b.addExecutable(.{ .name = "cartpole-study", .root_module = b.createModule(.{ .root_source_file = b.path("study.zig"), .target = b.graph.host, .optimize = .fast }) });
    study_exe.root_module.addImport("zinn", core);
    const study = b.addRunArtifact(study_exe);
    // Supplying checkpoint/calibration to train also supplies its unchanged outputs here.
    study.addFileArg(checkpoint);
    study.addFileArg(calibration);
    const study_dir = study.addOutputDirectoryArg("study");
    study.addArg(if (b.option(bool, "final-test", "Run frozen strategy on untouched final seeds") orelse false) "final" else "development");
    const quality_exe = b.addExecutable(.{ .name = "cartpole-quality-check", .root_module = b.createModule(.{ .root_source_file = b.path("check_quality.zig"), .target = b.graph.host, .optimize = .safe }) });
    const quality_check = b.addRunArtifact(quality_exe);
    quality_check.addFileArg(study_dir.path(b, "final.json"));
    b.step("quality-check", "Validate frozen final comparison (use -Dfinal-test=true)").dependOn(&quality_check.step);
    const study_step = b.step("study", "Quantization diagnostics and controlled policy comparisons");
    study_step.dependOn(&b.addInstallDirectory(.{ .source_dir = study_dir, .install_dir = .prefix, .install_subdir = "reports/study" }).step);

    const verifier = b.step("_policy-verify", "Independent generated integer verification");
    const policy = zinn.addModel(b, dep, .{ .name = "cartpole-policy", .model = b.path("model.zig"), .dataset = .{ .csv = .{ .training = calibration, .evaluation = calibration } }, .generated = .{ .source = source, .checkpoint = checkpoint, .metadata = metadata, .generate = train, .verify = verifier } });
    const verification = b.addExecutable(.{ .name = "policy-verify", .root_module = b.createModule(.{ .root_source_file = b.path("verify.zig"), .target = b.graph.host, .optimize = .safe }) });
    verification.root_module.addImport("policy", policy.createModule(b, b.graph.host, .safe));
    const verify = b.addRunArtifact(verification);
    verifier.dependOn(&verify.step);
    b.step("e2e", "All integer outputs versus independent reference").dependOn(policy.e2e);
    const reporter = b.addExecutable(.{ .name = "policy-report", .root_module = b.createModule(.{ .root_source_file = b.path("report.zig"), .target = b.graph.host, .optimize = .safe }) });
    const display_report = b.addRunArtifact(reporter);
    display_report.addFileArg(report);
    if (b.option(bool, "check-improvement", "Fail if learned policies do not improve the random baseline") orelse false) display_report.addArg("--check-improvement");
    display_report.has_side_effects = true;
    display_report.disable_zig_progress = true;
    b.step("evaluate", "Display saved held-out float/int8 rollout results").dependOn(&display_report.step);
    const ch32 = @import("ch32fun_zig");
    const fw = ch32.addFirmware(b, b.dependency("ch32fun_zig", .{}), .{ .name = "cartpole-policy", .root_source_file = b.path("firmware.zig") });
    fw.root_module.import_table.get("app").?.addImport("policy", policy.createModule(b, ch32.ch32Target(b), .small));
    const memory = zinn.addMemoryCheck(b, dep, .{ .name = "cartpole-policy", .elf = fw.getEmittedBin(), .flash_bytes = b.option(u32, "flash-bytes", "Final ELF Flash budget") orelse 16384 });
    const firmware = b.step("firmware", "Cross-build integer-only CH32V003 policy and final ELF budget; no flash");
    firmware.dependOn(memory.step);
    firmware.dependOn(policy.e2e);
    firmware.dependOn(&b.addInstallFile(fw.getEmittedBin(), "firmware/cartpole-policy.elf").step);
    const bin = fw.addObjCopy(.{ .format = .binary, .basename = "cartpole-policy.bin" });
    firmware.dependOn(&b.addInstallFile(bin.getOutput(), "firmware/cartpole-policy.bin").step);
    // Desktop graph follows after headless training/evaluation; owns no RL algorithms.
    if (b.graph.host.result.os.tag == .macos) {
        const ui_dep = b.dependency("mimoc_ui", .{ .optimize = .safe });
        const ui = ui_dep.module("mimoc_ui");
        const checkpoint_files = b.addWriteFiles();
        _ = checkpoint_files.addCopyFile(checkpoint, "policy.zinn");
        const checkpoint_module = b.createModule(.{ .root_source_file = checkpoint_files.add("checkpoint.zig", "pub const bytes=@embedFile(\"policy.zinn\");\n"), .target = b.graph.host, .optimize = .fast });
        const gui_integer = b.createModule(.{ .root_source_file = source, .target = b.graph.host, .optimize = .fast });
        gui_integer.addImport("zinn", core);
        const controller = b.createModule(.{ .root_source_file = b.path("app.zig"), .target = b.graph.host, .optimize = .fast });
        controller.addImport("zinn", core);
        controller.addImport("mimoc_ui", ui);
        controller.addImport("options", module.import_table.get("options").?);
        controller.addImport("initial_policy", checkpoint_module);
        controller.addImport("integer_policy", gui_integer);
        const desktop = b.addExecutable(.{ .name = "zinn-rl-lab", .root_module = b.createModule(.{ .root_source_file = b.path("main.zig"), .target = b.graph.host, .optimize = .safe }) });
        desktop.root_module.addImport("app", controller);
        desktop.root_module.addImport("mimoc_ui", ui);
        const window = b.createModule(.{ .root_source_file = ui_dep.path("src/platform/macos/window.zig"), .target = b.graph.host, .optimize = .safe });
        window.addImport("mimoc_ui", ui);
        desktop.root_module.addImport("desktop_window", window);
        desktop.root_module.addCSourceFile(.{ .file = ui_dep.path("src/platform/macos/window.m"), .flags = &.{"-fobjc-arc"} });
        desktop.root_module.addCSourceFile(.{ .file = b.path("window.m"), .flags = &.{"-fobjc-arc"} });
        desktop.root_module.linkFramework("AppKit", .{});
        desktop.root_module.linkFramework("Foundation", .{});
        desktop.root_module.link_libc = true;
        b.installArtifact(desktop);
        b.getInstallStep().dependOn(&b.addInstallFile(desktop.getEmittedBin(), "Zinn RL Lab.app/Contents/MacOS/zinn-rl-lab").step);
        b.getInstallStep().dependOn(&b.addInstallFile(b.path("Info.plist"), "Zinn RL Lab.app/Contents/Info.plist").step);
        const launch = b.addRunArtifact(desktop);
        launch.addPassthruArgs();
        b.step("run", "Automatic CartPole learning in mimoc-ui").dependOn(&launch.step);
        const test_controller = b.createModule(.{ .root_source_file = b.path("app.zig"), .target = b.graph.host, .optimize = test_options });
        test_controller.addImport("zinn", core);
        test_controller.addImport("mimoc_ui", ui);
        test_controller.addImport("options", module.import_table.get("options").?);
        test_controller.addImport("initial_policy", checkpoint_module);
        test_controller.addImport("integer_policy", gui_integer);
        const gui_tests = b.addTest(.{ .root_module = test_controller });
        b.step("test-gui", "Headless GUI controls and scheduling tests").dependOn(&b.addRunArtifact(gui_tests).step);
    }
}
